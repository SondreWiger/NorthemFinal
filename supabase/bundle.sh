#!/usr/bin/env bash
# Concatenate migrations + seed into apply_all.sql for the Supabase SQL editor.
set -euo pipefail
cd "$(dirname "$0")"
{ echo "-- Northem platform: every migration + seed in one file, for the Supabase SQL editor."
  echo "-- Generated by supabase/bundle.sh. Run once on an empty project."; echo
  for f in migrations/*.sql seed.sql; do echo "-- >>> $f"; cat "$f"; echo; done; } > apply_all.sql
echo "wrote supabase/apply_all.sql"
